export const DICTS = { en, nl, de, fr, es };

export const LANGS = [
  { code: "en", label: "English" },
  { code: "nl", label: "Nederlands" },
  { code: "de", label: "Deutsch" },
  { code: "fr", label: "Français" },
  { code: "es", label: "Español" },
];

export const DEFAULT_LANG = "en";

let current = DEFAULT_LANG;

export const setLang = (code) => {
  current = DICTS[code] ? code : DEFAULT_LANG;
  document.documentElement.lang = current;
  return current;
};

export const getLang = () => current;

const interpolate = (text, vars) =>
  vars ? text.replace(/\{(\w+)\}/g, (_, key) => (key in vars ? vars[key] : `{${key}}`)) : text;

/** Falls back to English, then to the key itself, so nothing renders blank. */
export const t = (key, vars) => {
  const value = DICTS[current]?.[key] ?? DICTS[DEFAULT_LANG][key];
  if (value === undefined) return key;
  return interpolate(value, vars);
};

/** Empty string is a deliberate "no verified answer" marker in the FAQ data. */
export const has = (key) => Boolean(DICTS[current]?.[key] || DICTS[DEFAULT_LANG][key]);

/**
 * Translates static markup: `data-i18n` sets text, `data-i18n-*` sets the
 * matching attribute (alt, placeholder, aria-label, content).
 */
export const applyI18n = (root = document) => {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  const attrs = [
    ["i18nAlt", "alt"],
    ["i18nPlaceholder", "placeholder"],
    ["i18nLabel", "aria-label"],
    ["i18nContent", "content"],
    ["i18nTitle", "title"],
  ];
  attrs.forEach(([dataKey, attr]) => {
    root.querySelectorAll(`[data-${dataKey.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}]`).forEach((el) => {
      el.setAttribute(attr, t(el.dataset[dataKey]));
    });
  });
};
